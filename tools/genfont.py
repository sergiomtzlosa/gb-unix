def main():
    missing = [c for c in map(chr, range(0x20, 0x7F)) if c not in G]
    extra = [c for c in G if not (0x20 <= ord(c) <= 0x7E)]
    if missing or extra:
        print("ERROR: glyph coverage mismatch:", missing, extra)
        sys.exit(1)
    for c, rows in G.items():
        if len(rows) != 8 or any(len(r) != 5 or set(r) - set('01') for r in rows):
            print("ERROR: bad glyph:", repr(c), rows)
            sys.exit(1)

    lines = [
        '; GENERATED by tools/genfont.py - do not edit by hand.',
        '; 5x8 glyphs, chars 0x20-0x7E, one 1bpp byte per row (bits 7-3).',
        '; 95 tiles x 8 bytes = 760 bytes. Expanded to 2bpp by font.asm.',
        '',
        'section "fontdata", rom0',
        '',
        'fontdata::',
    ]
    for code in range(0x20, 0x7F):
        ch = chr(code)
        rows = G[ch]
        vals = [int(r, 2) << 3 for r in rows]
        disp = ch if ch not in ('\\', ';') else ' '
        lines.append('    db %s ; %r' % (
            ', '.join('$%02X' % v for v in vals), disp))
    lines.append('')
    with open('src/fontdata.asm', 'w') as f:
        f.write('\n'.join(lines))

    # visual check: print every 16th glyph as ascii art
    for code in range(0x20, 0x7F, 16):
        chars = [chr(min(code + i, 0x7E)) for i in range(16)]
        print(''.join(chars))
        for r in range(8):
            print(''.join(G[c][r].replace('0', '.').replace('1', '#')
                          for c in chars))
        print()

if __name__ == '__main__':
    main()
