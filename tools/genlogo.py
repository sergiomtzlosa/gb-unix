#!/usr/bin/env python3
"""Generate src/logodata.asm — splash logo tiles for gb-unix (20x18 engine).

The splash paints a 160x24 pixel logo (3 tile rows x 20 tiles) above the
regular text. The logo uses the 60 VRAM tiles 190-249, which are free: the
font occupies tiles 0-94 (normal) and 95-189 (inverted copy).

Font tiles are 1bpp expanded to 2bpp at boot, so this data is one plane-0
byte per pixel row (MSB = leftmost pixel); font.asm expands it the same way.

Layout inside the 160x24 area:
  - Tux 24x24 at pixel x 8..31   (tile cols 1-3)
  - "GB-UNIX" block letters at 2x (16x16 each) at pixel x 48..143
  - 'g' pixels are a checkerboard dither (perceived gray on 1bpp)
"""
import sys

# Tux, 24 pixels wide x 32 rows; rows 17-24 are dropped to fit 24 rows.
_TUX32 = [
".......##########.......",
".....##############.....",
"....################....",
"...##################...",
"..####################..",
"..###.....####.....###..",
"..###..##.####.##..###..",
"..###..##.####.##..###..",
"..###.....####.....###..",
"..####################..",
"..####gggggggggggg####..",
"...###gggggggggggg###...",
"....###gggggggggg###....",
"...####..........####...",
"..#####..........#####..",
"..####............####..",
".######..........######.",
".######..........######.",
".#####............#####.",
".#####............#####.",
".####..............####.",
".####..............####.",
".####..............####.",
".####..............####.",
".#####............#####.",
".#####............#####.",
"..####............####..",
"..######........######..",
"..######........######..",
"...gggggggg..gggggggg...",
"...gggggggg..gggggggg...",
"....gggggg....gggggg....",
]
TUX = _TUX32[:17] + _TUX32[25:]

LETTERS = {
"G": [".#####..",
      "#.....#.",
      "#.......",
      "#..####.",
      "#.....#.",
      "#.....#.",
      ".#####..",
      "......."],
"B": ["######..",
      "#.....#.",
      "#.....#.",
      "######..",
      "#.....#.",
      "#.....#.",
      "######..",
      "......."],
"-": ["........",
      "........",
      "........",
      "..####..",
      "........",
      "........",
      "........",
      "........"],
"U": ["#.....#.",
      "#.....#.",
      "#.....#.",
      "#.....#.",
      "#.....#.",
      "#.....#.",
      ".#####..",
      "......."],
"N": ["#.....#.",
      "##....#.",
      "#.#...#.",
      "#..#..#.",
      "#...#.#.",
      "#....##.",
      "#.....#.",
      "......."],
"I": [".#####..",
      "...#....",
      "...#....",
      "...#....",
      "...#....",
      "...#....",
      ".#####..",
      "......."],
"X": ["#.....#.",
      ".#...#..",
      "..#.#...",
      "...#....",
      "..#.#...",
      ".#...#..",
      "#.....#.",
      "......."],
}

TILE_COLS = 20          # tiles per logo row (= screen width)
LOGO_ROWS = 3           # tile rows 0-2
TILE_BASE = 190         # first free VRAM tile after font + inverted copy
LOGO = "GB-UNIX"
TUX_X = 8               # pixel x of Tux (8px screen margin)
LETTER_X = 40           # 8px gap after Tux; logo block is centred


def main():
    if len(TUX) != 24 or any(len(r) != 24 or set(r) - set('.#g') for r in TUX):
        print("ERROR: bad TUX art", file=sys.stderr)
        sys.exit(1)
    for ch, rows in LETTERS.items():
        if len(rows) != 8 or any(set(r) - set('.#') or len(r) > 8 for r in rows):
            print("ERROR: bad letter", ch, file=sys.stderr)
            sys.exit(1)
    norm = {ch: [r.ljust(8, '.') for r in rows] for ch, rows in LETTERS.items()}

    # grid[r][c] = list of 8 ints (one per pixel row, MSB = leftmost)
    grid = [[[0] * 8 for _ in range(TILE_COLS)] for _ in range(LOGO_ROWS)]

    def px(x, y, v):
        if not (0 <= x < 160 and 0 <= y < 24):
            print("ERROR: pixel out of bounds", x, y, file=sys.stderr)
            sys.exit(1)
        if v:
            grid[y // 8][x // 8][y % 8] |= 0x80 >> (x % 8)

    # Tux (1:1 pixels; 'g' = checkerboard dither)
    for y, row in enumerate(TUX):
        for x, chv in enumerate(row):
            if chv == '#':
                px(TUX_X + x, y, 1)
            elif chv == 'g':
                px(TUX_X + x, y, (x + y) & 1)

    # letters at 2x scale, vertically centred (glyph art y 4..17)
    for i, chv in enumerate(LOGO):
        rows = norm[chv]
        for ly, line in enumerate(rows):
            for lx, v in enumerate(line):
                if v == '#':
                    for dy in (0, 1):
                        for dx in (0, 1):
                            px(LETTER_X + i * 16 + lx * 2 + dx,
                               4 + ly * 2 + dy, 1)

    ntiles = TILE_COLS * LOGO_ROWS
    lines = [
        '; GENERATED by tools/genlogo.py - do not edit by hand.',
        '; Splash logo: 160x24 px (3 tile rows x 20 tiles), 1bpp plane 0.',
        '; Tiles are uploaded to VRAM tiles 190-249 by font.asm; logo_map',
        '; is copied into screen_buf rows 0-2 by the title screen.',
        '',
        'def LOGO_TILE_BASE equ %d' % TILE_BASE,
        'def LOGO_ROWS      equ %d' % LOGO_ROWS,
        'def LOGO_TILES     equ %d' % ntiles,
        '',
        'section "logodata", rom0',
        '',
        'logotiles::',
    ]
    for r in range(LOGO_ROWS):
        lines.append('    ; tile row %d' % r)
        for c in range(TILE_COLS):
            b = grid[r][c]
            lines.append('    db ' + ', '.join('$%02X' % v for v in b))
    lines.append('')
    lines.append('logo_map::')
    for r in range(LOGO_ROWS):
        vals = [TILE_BASE + r * TILE_COLS + c for c in range(TILE_COLS)]
        lines.append('    db ' + ', '.join('%d' % v for v in vals))
    lines.append('')
    with open('src/logodata.asm', 'w') as f:
        f.write('\n'.join(lines))

    # ASCII preview (1 char = 1 px)
    print('splash logo preview (160x24):')
    for y in range(24):
        line = ''
        for x in range(160):
            on = grid[y // 8][x // 8][y % 8] >> (7 - (x % 8)) & 1
            line += '#' if on else '.'
        print(line)


if __name__ == '__main__':
    main()
